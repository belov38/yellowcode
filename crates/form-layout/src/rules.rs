impl Rules {
    pub fn float_content_w(&self, wn: f32, w: f32) -> f32 {
        let limit = self.float_w_k * w + self.float_w_b;
        wn.min(limit).max(self.float_min_w).round()
    }

    pub fn float_heights(&self, content_h: f32, ws_h: f32) -> (f32, f32) {
        let chrome = self.float_head_h + self.float_foot_h;
        let limit = (ws_h - self.float_margin_b).max(chrome);
        let h = (content_h + chrome).min(limit);
        (h, h - chrome)
    }

    pub fn float_pos(&self, vw: f32, ws_h: f32, w: f32, h: f32) -> (f32, f32) {
        (
            ((vw - w) / 2.0).floor() + 1.0,
            self.workspace_top + ((ws_h - h) / 2.0).floor() + 1.0,
        )
    }
}

pub fn rules(i: Interface) -> Result<&'static Rules, LayoutError> {
    match i {
        Interface::Taxi => Ok(&TAXI),
        Interface::V85 => Err(LayoutError::Unsupported("interface 8.5: stage W9")),
    }
}
